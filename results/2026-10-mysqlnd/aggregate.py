#!/usr/bin/env python3
"""Tables of the mysqlnd statistics series: FrankenPHP + MySQL, statistics on, off, and on with atomic counters.
Reads data/raw/<series>-<variant>.jsonl next to this script and prints Markdown.
Records are in pass order; a pass holds one record per concurrency and rate."""
import json, statistics as st, sys
from pathlib import Path

RAW = Path(__file__).parent / 'data' / 'raw'
VARIANTS = [('stats-on', 'statistics on (default)'), ('stats-off', '`mysqlnd.collect_statistics=0`'),
            ('atomic-on', 'statistics on, atomic counters')]


def load(series, v):
    return [json.loads(l) for l in (RAW / f'{series}-{v}.jsonl').read_text().splitlines() if l.strip()]


def m(r):
    """CPU per request: cgroup CPU time between the snapshots right before and right after wrk, divided by the requests wrk completed."""
    w, cw = r['wrk'], r['cpu_window']
    n = w['requests']
    return {'scpu': cw['stack'] / n * 1000, 'dbcpu': cw['blog-mysql'] / n * 1000,
            'rps': n / (w['duration_us'] / 1e6), 'p99': w['p99_us'] / 1000}


def points(series):
    """{variant: {point: [metrics per pass]}}, point = rate (or 'C=<c>' without a rate)."""
    out = {}
    for v, _ in VARIANTS:
        d = out.setdefault(v, {})
        for r in load(series, v):
            d.setdefault(r['rate'] or f"C={r['c']}", []).append(m(r))
    return out


def pct(x):
    return f'{(x - 1) * 100:+.1f}%'


def table(series, title):
    P = points(series)
    keys = list(P['stats-on'])
    print(f'\n## {title}\n')
    print('Stack CPU per request (FrankenPHP container), median of the passes [min–max]; database CPU and req/s, median.\n')
    print('| point | variant | passes | stack CPU, ms | DB CPU, ms | req/s | p99, ms |')
    print('|---|---|---:|---:|---:|---:|---:|')
    for k in keys:
        for v, name in VARIANTS:
            runs = P[v][k]
            s = [x['scpu'] for x in runs]
            pt = f'{k} req/s' if isinstance(k, int) else k
            print(f"| {pt} | {name} | {len(runs)} | {st.median(s):.3f} [{min(s):.3f}–{max(s):.3f}] | "
                  f"{st.median(x['dbcpu'] for x in runs):.3f} | {st.median(x['rps'] for x in runs):.0f} | "
                  f"{st.median(x['p99'] for x in runs):.1f} |")
    print('\nStack CPU against statistics off, per pass (the variants of a pass ran one after another): median of the per-pass ratios [min–max].\n')
    print('| point | statistics on | statistics on, atomic counters |')
    print('|---|---:|---:|')
    for k in keys:
        off = [x['scpu'] for x in P['stats-off'][k]]
        cells = []
        for v in ('stats-on', 'atomic-on'):
            r = [a['scpu'] / b for a, b in zip(P[v][k], off)]
            cells.append(f'{pct(st.median(r))} [{pct(min(r))} to {pct(max(r))}]')
        pt = f'{k} req/s' if isinstance(k, int) else k
        print(f'| {pt} | {cells[0]} | {cells[1]} |')


print('# mysqlnd statistics in ZTS builds: FrankenPHP + MySQL\n')
print('Generated by `aggregate.py` from `data/raw/`; do not edit by hand.')
table('memory', '50 clients (48 connections), closed loop: the database is saturated')
table('rate', 'Fixed request rates over 48 connections (wrk2)')
